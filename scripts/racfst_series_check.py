"""Real-only accuracy on the RACFST database: random repeated 5-fold CV vs leave-one-series-out CV.

    python scripts/racfst_series_check.py --out paper/generated/series_numbers.tex

The 56 tests come from a small number of test series (same section, D and t); specimens within a series differ
mainly in axial load ratio and replacement ratio. Random folds therefore place sister specimens in both training
and test sets. This script quantifies how much lower the error is under random folds than when a whole series is
held out. It uses the same features as configs/racfst.json (derived ratios included) and fold-wise median
imputation, which is simpler than the pipeline's imputation branches; it is a descriptive check, not part of E0.
"""
import argparse
import json
import os

import numpy as np
import pandas as pd
import xgboost as xgb
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, r2_score
from sklearn.model_selection import LeaveOneGroupOut, RepeatedKFold

PROJECT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEED = 2026


def models():
    return {'RF': RandomForestRegressor(n_estimators=400, random_state=SEED, n_jobs=6),
            'XGB': xgb.XGBRegressor(n_estimators=350, max_depth=4, learning_rate=0.05, subsample=0.9,
                                    colsample_bytree=0.9, random_state=SEED, n_jobs=6)}


def evaluate(X, y, splits):
    mae = {k: [] for k in models()}
    pred = {k: np.full(len(y), np.nan) for k in models()}
    for tr, te in splits:
        Xtr, Xte = X.iloc[tr], X.iloc[te]
        med = Xtr.median()
        Xtr, Xte = Xtr.fillna(med), Xte.fillna(med)
        for name, m in models().items():
            m.fit(Xtr, y.iloc[tr])
            p = m.predict(Xte)
            mae[name].append(mean_absolute_error(y.iloc[te], p))
            pred[name][te] = p
    return {k: float(np.mean(v)) for k, v in mae.items()}, pred


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--config', default=os.path.join(PROJECT, 'configs', 'racfst.json'))
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    cfg = json.load(open(a.config, encoding='utf-8'))
    df = pd.read_excel(os.path.join(PROJECT, cfg['data']))
    df = df.drop(columns=[cfg['id_column']])
    for col, expr in cfg['derived'].items():
        df[col] = df.eval(expr)
    series = df.groupby(['Section', 'D_mm', 't_mm']).ngroup().values
    df['Section'] = (df['Section'] == df['Section'].unique()[0]).astype(int)
    y = df.pop(cfg['regression_target'])

    rand, _ = evaluate(df, y, list(RepeatedKFold(n_splits=5, n_repeats=3, random_state=SEED).split(df)))
    logo, pred = evaluate(df, y, list(LeaveOneGroupOut().split(df, y, series)))
    r2 = {k: r2_score(y, p) for k, p in pred.items()}
    m = {'seriesCount': str(len(set(series))), 'seriesMaeRandRF': f"{rand['RF']:.1f}",
         'seriesMaeRandXGB': f"{rand['XGB']:.1f}", 'seriesMaeLosoRF': f"{logo['RF']:.1f}",
         'seriesMaeLosoXGB': f"{logo['XGB']:.1f}", 'seriesRtwoLosoRF': f"{r2['RF']:.2f}",
         'seriesRtwoLosoXGB': f"{r2['XGB']:.2f}", 'puMean': f"{y.mean():.1f}"}
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, 'w') as fh:
        fh.write('% generated by scripts/racfst_series_check.py\n')
        for k, v in m.items():
            fh.write(f'\\newcommand{{\\{k}}}{{{v}}}\n')
    for k, v in m.items():
        print(f'{k} = {v}')


if __name__ == '__main__':
    main()
